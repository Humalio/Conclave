/**
 * Permission engine (SPECIFICATION §8, §9). One function decides every call, the
 * simulator and the inspector. Default deny; deny always wins; the app key caps.
 *
 * Resources are "<kind>:<pattern>":
 *   path:/vault/Projects/**   tool:file_read   agent:agent-x   room:*   team:*   share:*   channel:*
 * Path patterns: "*" matches inside one segment, "**" matches zero or more segments.
 * Other kinds: "*" matches any run of characters.
 * Actions may use a trailing wildcard: "fs.*", "*".
 */

export interface Rule {
  id: string;
  effect: 'allow' | 'deny';
  actions: string[];
  resource: string;
  from_template?: string | null;
  note?: string | null;
  /** Set on rules generated by a team; they are removed with the membership or the team. */
  team_id?: string | null;
  /** Temporary grants only: the rule applies in [not_before, not_after), checked at decision time. */
  not_before?: number;
  not_after?: number;
}

export type DecisionSource = 'session_key' | 'app_key_cap' | 'default' | 'link' | 'paused';

/** Actions that change state; a paused team's resources refuse them. */
const PAUSABLE = /^(message.send|room.post|channel.|share.(create|upload|comment|suggest|promote)|fs.(create|update|rename|delete|restore)|task.|team.(report|complete|recruit|plan|ask)|graph.(write|review))/;
export interface AuthorizeOpts { isPaused?: (resource: string, rule: Rule) => boolean }

export interface Decision {
  allowed: boolean;
  action: string;
  resource: string;
  /** Which rule decided, if any. */
  rule: Rule | null;
  source: DecisionSource;
  reason: string;
}

export const RESOURCE_KINDS = ['path', 'tool', 'agent', 'room', 'team', 'share', 'channel', 'graph'] as const;

export function parseResource(r: string): { kind: string; pattern: string } {
  const i = r.indexOf(':');
  if (i <= 0) throw new Error(`invalid resource "${r}": expected <kind>:<pattern>`);
  const kind = r.slice(0, i), pattern = r.slice(i + 1);
  if (!(RESOURCE_KINDS as readonly string[]).includes(kind)) throw new Error(`unknown resource kind "${kind}"`);
  if (!pattern) throw new Error(`invalid resource "${r}": empty pattern`);
  if (kind === 'path' && !pattern.startsWith('/')) throw new Error(`path pattern must start with "/": "${r}"`);
  return { kind, pattern };
}

export function actionMatches(pattern: string, action: string): boolean {
  if (pattern === '*') return true;
  if (pattern.endsWith('.*')) return action.startsWith(pattern.slice(0, -1));
  return pattern === action;
}

function segments(p: string): string[] { return p.split('/').filter((s) => s.length > 0); }

function globSegment(pat: string, seg: string): boolean {
  if (pat === '*') return true;
  if (!pat.includes('*')) return pat === seg;
  const re = new RegExp('^' + pat.split('*').map(escapeRe).join('[^/]*') + '$');
  return re.test(seg);
}
function escapeRe(s: string): string { return s.replace(/[.+?^${}()|[\]\\]/g, '\\$&'); }

/** Does path pattern match a concrete, normalised path? */
export function pathMatches(pattern: string, path: string): boolean {
  const ps = segments(pattern), xs = segments(path);
  const memo = new Map<string, boolean>();
  const go = (i: number, j: number): boolean => {
    const k = `${i},${j}`;
    const hit = memo.get(k); if (hit !== undefined) return hit;
    let r: boolean;
    if (i === ps.length) r = j === xs.length;
    else if (ps[i] === '**') r = go(i + 1, j) || (j < xs.length && go(i, j + 1));
    else r = j < xs.length && globSegment(ps[i]!, xs[j]!) && go(i + 1, j + 1);
    memo.set(k, r); return r;
  };
  return go(0, 0);
}

/**
 * Could this path pattern match something strictly below `dir`?
 * Used to let a key list the parents of folders it was granted.
 */
export function pathReachesBelow(pattern: string, dir: string): boolean {
  const ps = segments(pattern), ds = segments(dir);
  for (let i = 0; i < ds.length; i++) {
    const p = ps[i];
    if (p === undefined) return false;
    if (p === '**') return true;
    if (!globSegment(p, ds[i]!)) return false;
  }
  return ps.length > ds.length;
}

function globAny(pattern: string, value: string): boolean {
  if (pattern === '*') return true;
  return new RegExp('^' + pattern.split('*').map(escapeRe).join('.*') + '$').test(value);
}

/**
 * Does path pattern `outer` match every path that `inner` can match? Conservative: true only when it is provable
 * (equal patterns, a concrete inner path that outer matches, or an outer of the form <prefix>/** whose prefix the
 * inner pattern starts with). Anything harder counts as not covered.
 */
export function pathCovers(outer: string, inner: string): boolean {
  if (outer === inner) return true;
  if (!inner.includes('*')) return pathMatches(outer, inner);
  const os = segments(outer), is = segments(inner);
  const k = os.indexOf('**');
  if (k < 0 || k !== os.length - 1 || is.length < k) return false;
  for (let i = 0; i < k; i++) {
    const o = os[i]!, n = is[i]!;
    if (n === o) continue;
    if (n.includes('*') || !globSegment(o, n)) return false;
  }
  return true;
}
/** Resource-pattern version of pathCovers, for every resource kind. */
export function resourceCovers(outer: string, inner: string): boolean {
  const a = parseResource(outer), b = parseResource(inner);
  if (a.kind !== b.kind) return false;
  if (a.kind === 'path') return pathCovers(a.pattern, b.pattern);
  if (a.pattern === b.pattern || a.pattern === '*') return true;
  if (!b.pattern.includes('*')) return globAny(a.pattern, b.pattern);
  const star = a.pattern.indexOf('*');
  return star === a.pattern.length - 1 && b.pattern.startsWith(a.pattern.slice(0, -1));
}
/** Does action pattern `outer` include every action `inner` names? */
export function actionCovers(outer: string, inner: string): boolean {
  if (outer === '*' || outer === inner) return true;
  return outer.endsWith('.*') && inner !== '*' && inner.startsWith(outer.slice(0, -1));
}
/**
 * Is `action` on everything `resource` can match granted by one standing allow rule? Deny rules are not weighed
 * here: callers that hand rules on (recruiting) copy the deny rules along, and deny always wins.
 */
export function allowsAll(rules: Rule[], action: string, resource: string): boolean {
  return rules.some((r) => r.effect === 'allow' && r.not_after === undefined && r.actions.some((a) => actionCovers(a, action)) && resourceCovers(r.resource, resource));
}

/**
 * What changed between two rule lists, in words an agent can act on: "added fs.create, fs.update on
 * path:/vault/X/**", "removed message.send on agent:…", "new deny fs.read on …". Temporary grants are not
 * compared here. An empty list means the effective rules are the same (no notice is needed).
 */
export function describeRuleChanges(before: Pick<Rule, 'effect' | 'actions' | 'resource'>[], after: Pick<Rule, 'effect' | 'actions' | 'resource'>[], max = 4): string[] {
  const index = (L: Pick<Rule, 'effect' | 'actions' | 'resource'>[]) => {
    const m = new Map<string, Set<string>>();
    for (const r of L) { const k = `${r.effect}\u0000${r.resource}`; const s = m.get(k) ?? new Set<string>(); for (const a of r.actions) s.add(a); m.set(k, s); }
    return m;
  };
  const B = index(before), A = index(after), out: string[] = [];
  const say = (verb: string, effect: string, acts: string[], resource: string) => out.push(`${verb} ${effect === 'deny' ? 'deny ' : ''}${acts.sort().join(', ')} on ${resource}`);
  for (const [k, acts] of A) {
    const [effect, resource] = k.split('\u0000') as [string, string], had = B.get(k) ?? new Set<string>();
    const add = [...acts].filter((a) => !had.has(a));
    if (add.length) say('added', effect, add, resource);
  }
  for (const [k, acts] of B) {
    const [effect, resource] = k.split('\u0000') as [string, string], has = A.get(k) ?? new Set<string>();
    const gone = [...acts].filter((a) => !has.has(a));
    if (gone.length) say('removed', effect, gone, resource);
  }
  return out.length > max ? [...out.slice(0, max), `and ${out.length - max} more`] : out;
}

export function resourceMatches(rulePattern: string, resource: string): boolean {
  const a = parseResource(rulePattern), b = parseResource(resource);
  if (a.kind !== b.kind) return false;
  return a.kind === 'path' ? pathMatches(a.pattern, b.pattern) : globAny(a.pattern, b.pattern);
}

function ruleApplies(rule: Rule, action: string, resource: string): boolean {
  if (rule.not_after !== undefined) {
    const now = Date.now();
    if (now >= rule.not_after || (rule.not_before !== undefined && now < rule.not_before)) return false;
  }
  return rule.actions.some((a) => actionMatches(a, action)) && resourceMatches(rule.resource, resource);
}

function evalList(rules: Rule[], action: string, resource: string): { effect: 'allow' | 'deny' | 'none'; rule: Rule | null } {
  let allow: Rule | null = null;
  for (const r of rules) {
    if (!ruleApplies(r, action, resource)) continue;
    if (r.effect === 'deny') return { effect: 'deny', rule: r };
    allow ??= r;
  }
  return allow ? { effect: 'allow', rule: allow } : { effect: 'none', rule: null };
}

/**
 * Decide one action on one resource.
 * @param sessionRules the session key's rules
 * @param capRules the app key's rules; an empty list means "no cap"
 */
export function authorize(sessionRules: Rule[], capRules: Rule[], action: string, resource: string, opts?: AuthorizeOpts): Decision {
  parseResource(resource);
  const s = evalList(sessionRules, action, resource);
  if (s.effect === 'deny') return { allowed: false, action, resource, rule: s.rule, source: 'session_key', reason: `denied by rule ${s.rule!.id}` };
  if (s.effect === 'none') return { allowed: false, action, resource, rule: null, source: 'default', reason: 'no rule allows it (default deny)' };
  if (capRules.length > 0) {
    const c = evalList(capRules, action, resource);
    if (c.effect === 'deny') return { allowed: false, action, resource, rule: c.rule, source: 'app_key_cap', reason: `denied by the app key's cap, rule ${c.rule!.id}` };
    if (c.effect === 'none') return { allowed: false, action, resource, rule: null, source: 'app_key_cap', reason: "outside the app key's cap" };
  }
  if (opts?.isPaused && PAUSABLE.test(action) && opts.isPaused(resource, s.rule!)) return { allowed: false, action, resource, rule: s.rule, source: 'paused', reason: 'the team is paused' };
  return { allowed: true, action, resource, rule: s.rule, source: s.rule!.id.startsWith('link:') ? 'link' : 'session_key', reason: `allowed by rule ${s.rule!.id}` };
}

/** Does an explicit deny rule of the session key or the app key match this action and resource? (Default tools only.) */
export function explicitlyDenied(sessionRules: Rule[], capRules: Rule[], action: string, resource: string): boolean {
  parseResource(resource);
  return evalList(sessionRules, action, resource).effect === 'deny' || evalList(capRules, action, resource).effect === 'deny';
}

/**
 * True if `action` is allowed on the directory itself or could be allowed on
 * something below it (so the directory may be shown in listings). Denies on the
 * directory subtree ("dir/**") still win.
 */
export function canReach(sessionRules: Rule[], capRules: Rule[], action: string, dirPath: string): boolean {
  if (authorize(sessionRules, capRules, action, `path:${dirPath}`).allowed) return true;
  // A temporary grant counts only inside its window, as authorize() decides it.
  const now = Date.now();
  const live = (r: Rule) => r.not_after === undefined || (now < r.not_after && (r.not_before === undefined || now >= r.not_before));
  const reaches = (rules: Rule[]) => rules.some((r) => r.effect === 'allow' && live(r) && r.actions.some((a) => actionMatches(a, action))
    && r.resource.startsWith('path:') && pathReachesBelow(r.resource.slice(5), dirPath));
  const subtreeDenied = (rules: Rule[]) => rules.some((r) => r.effect === 'deny' && r.actions.some((a) => actionMatches(a, action))
    && r.resource.startsWith('path:') && pathMatches(r.resource.slice(5), dirPath) && r.resource.endsWith('/**'));
  if (!reaches(sessionRules) || subtreeDenied(sessionRules)) return false;
  if (capRules.length > 0 && (!(reaches(capRules) || authorize(capRules, [], action, `path:${dirPath}`).allowed) || subtreeDenied(capRules))) return false;
  return true;
}

/** Validate a rule list coming from the admin API. Throws with a readable message. */
export function validateRules(rules: unknown): asserts rules is Omit<Rule, 'id'>[] {
  if (!Array.isArray(rules)) throw new Error('rules must be an array');
  for (const [i, r] of rules.entries()) {
    const x = r as Partial<Rule>;
    if (x.effect !== 'allow' && x.effect !== 'deny') throw new Error(`rule ${i + 1}: effect must be allow or deny`);
    if (!Array.isArray(x.actions) || x.actions.length === 0 || !x.actions.every((a) => typeof a === 'string' && /^[a-z_]+(\.[a-z_*]+)*$|^\*$/.test(a))) {
      throw new Error(`rule ${i + 1}: actions must be a non-empty list like ["fs.read"]`);
    }
    if (typeof x.resource !== 'string') throw new Error(`rule ${i + 1}: resource is required`);
    try { parseResource(x.resource); } catch (e) { throw new Error(`rule ${i + 1}: ${(e as Error).message}`); }
  }
}
