#!/usr/bin/env node
/**
 * The 1.0 baseline (docs/proposals/v1-release.md §2). A release tool, not part of the hub: run it from server/ in a
 * checkout, never from dist/ or an image (the Dockerfile copies no test/). It imports the 0.x runner from
 * test/fixtures/v0/db0.ts, so it needs Node 24's type stripping.
 *
 *   node scripts/v1-baseline.mjs            writes src/db/migrations/0100_v1_baseline.sql: a fresh database built by the
 *                                           0.x runner from the 56 migrations of 0.x (test/fixtures/v0), dumped from
 *                                           sqlite_master as stored (tables, indexes, views, triggers) plus its seed rows
 *   node scripts/v1-baseline.mjs --legacy   prints the 56 (version, checksum) pairs the runner keeps as LEGACY_0X
 *   node scripts/v1-baseline.mjs --check F  compares database file F (read-only) with the baseline, as the runner's
 *                                           recognition does; prints each differing object, exit code 1 if any differ
 */
import { DatabaseSync } from 'node:sqlite';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { migrate0, V0_MIGRATIONS } from '../test/fixtures/v0/db0.ts';

const server = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(server, 'src', 'db', 'migrations', '0100_v1_baseline.sql');
const eol = (s) => s.replace(/\r\n/g, '\n');
const ORDER = ['table', 'index', 'view', 'trigger'];

/** A fresh database built from the 0.x chain, as a 0.x hub builds it (foreign keys on). */
export function oldChain() {
  const db = new DatabaseSync(':memory:');
  db.exec('PRAGMA foreign_keys=ON');
  migrate0(db, V0_MIGRATIONS);
  return db;
}

/** The baseline text for a database: its schema as stored, then the rows of every non-empty table. */
export function dump(db) {
  const objs = db.prepare(`SELECT type, name, sql FROM sqlite_master
    WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite\\_%' ESCAPE '\\' AND name <> 'schema_migrations' ORDER BY rowid`).all();
  const out = ['-- Conclave 1.0 baseline: the schema and seed rows of the 56 migrations of 0.x (0c507c8), as SQLite stores them.',
    '-- Generated by server/scripts/v1-baseline.mjs; do not edit. Later migrations are 0101 and up.', ''];
  for (const type of ORDER) {
    for (const o of objs.filter((r) => r.type === type)) out.push(`${eol(o.sql)};`);
    if (type !== 'table') continue;
    // Seed rows go right after the tables, before any index or trigger, as the migrations inserted them.
    for (const o of objs.filter((r) => r.type === 'table')) {
      const cols = db.prepare(`SELECT name FROM pragma_table_info(?) ORDER BY cid`).all(o.name).map((c) => c.name);
      const q = cols.map((c) => `quote("${c}")`).join(` || ',' || `);
      const rows = db.prepare(`SELECT ${q} AS v FROM "${o.name}" ORDER BY rowid`).all();
      for (const r of rows) out.push(`INSERT INTO ${o.name}(${cols.join(', ')}) VALUES (${eol(r.v)});`);
    }
  }
  return out.join('\n') + '\n';
}

/** sqlite_master keyed by (type, name), without schema_migrations and sqlite_sequence, as the runner compares it. */
function schemaOf(db) {
  const m = new Map();
  for (const r of db.prepare('SELECT type, name, tbl_name, sql FROM sqlite_master').all()) {
    if (r.name === 'sqlite_sequence' || /^sqlite_stat\d$/.test(r.name) || r.tbl_name === 'schema_migrations') continue;
    m.set(`${r.type} ${r.name}`, `${r.tbl_name}\n${r.sql === null ? '' : eol(r.sql)}`);
  }
  return m;
}

function check(file) {
  const want = new DatabaseSync(':memory:');
  want.exec(readFileSync(OUT, 'utf8'));
  const have = new DatabaseSync(file, { readOnly: true });
  const a = schemaOf(want), b = schemaOf(have);
  const diff = [];
  for (const [k, v] of a) if (!b.has(k)) diff.push(`missing ${k}`); else if (b.get(k) !== v) diff.push(`differs ${k}`);
  for (const k of b.keys()) if (!a.has(k)) diff.push(`extra ${k}`);
  console.log(diff.length ? diff.join('\n') : `${file}: schema equals the baseline (${a.size} objects)`);
  process.exitCode = diff.length ? 1 : 0;
}

function legacy() {
  for (const f of readdirSync(V0_MIGRATIONS).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort()) {
    const sum = createHash('sha256').update(eol(readFileSync(join(V0_MIGRATIONS, f), 'utf8'))).digest('hex');
    console.log(`  [${Number(f.slice(0, 4))}, '${sum}'],`);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const [flag, arg] = process.argv.slice(2);
  if (flag === '--check') check(arg);
  else if (flag === '--legacy') legacy();
  else { writeFileSync(OUT, dump(oldChain())); console.log(`wrote ${OUT}`); }
}
